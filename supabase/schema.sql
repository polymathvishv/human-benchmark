-- 1. Create Profiles Table
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  username TEXT UNIQUE NOT NULL,
  avatar_color TEXT DEFAULT 'linear-gradient(135deg, #3b82f6 0%, #8b5cf6 100%)',
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Enable Row Level Security (RLS)
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

-- 2. Profiles Security Policies
-- Anyone can view public profiles
CREATE POLICY "Public profiles are viewable by everyone" 
ON public.profiles FOR SELECT 
USING (true);

-- Users can insert their own profile
CREATE POLICY "Users can insert their own profile" 
ON public.profiles FOR INSERT 
WITH CHECK (auth.uid() = id);

-- Users can update their own profile
CREATE POLICY "Users can update their own profile" 
ON public.profiles FOR UPDATE 
USING (auth.uid() = id);

-- 3. Automatic Profile Creation Trigger on Sign Up
CREATE OR REPLACE FUNCTION public.handle_new_user() 
RETURNS TRIGGER AS $$
DECLARE
  initial_username TEXT;
BEGIN
  -- Extract username from user_metadata or fallback to User_XXXX
  initial_username := COALESCE(
    NULLIF(TRIM(new.raw_user_meta_data->>'username'), ''),
    'User_' || SUBSTRING(new.id::text, 1, 6)
  );

  INSERT INTO public.profiles (id, username, avatar_color)
  VALUES (
    new.id,
    initial_username,
    'linear-gradient(135deg, #3b82f6 0%, #8b5cf6 100%)'
  )
  ON CONFLICT (id) DO NOTHING;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Drop trigger if exists and recreate
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;

CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- 4. Create Scores Table (Ready for Cloud Sync)
CREATE TABLE IF NOT EXISTS public.scores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  game_id TEXT NOT NULL,
  score NUMERIC NOT NULL,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Enable RLS on scores
ALTER TABLE public.scores ENABLE ROW LEVEL SECURITY;

-- Anyone can read scores (for leaderboards and stats)
CREATE POLICY "Scores are readable by everyone" 
ON public.scores FOR SELECT 
USING (true);

-- Users can insert their own scores
CREATE POLICY "Users can insert their own scores" 
ON public.scores FOR INSERT 
WITH CHECK (auth.uid() = user_id);

-- Create index on game_id and score for fast querying
CREATE INDEX IF NOT EXISTS idx_scores_game_score ON public.scores(game_id, score);
CREATE INDEX IF NOT EXISTS idx_scores_user ON public.scores(user_id);
CREATE INDEX IF NOT EXISTS idx_scores_game_created ON public.scores(game_id, created_at DESC);

-- Enable Supabase Realtime for instant leaderboard updates
ALTER PUBLICATION supabase_realtime ADD TABLE public.scores;


-- ==============================================================================
-- BATTLE ROOMS FEATURE (Multiplayer Cognitive Test Battles)
-- ==============================================================================

-- 5. Battle Rooms Table
CREATE TABLE IF NOT EXISTS public.battle_rooms (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  room_code TEXT UNIQUE NOT NULL,          -- 8-char alphanumeric code for URL
  host_name TEXT NOT NULL DEFAULT 'Host',  -- Creator display name (no auth required)
  game_id TEXT NOT NULL,                   -- Which test (e.g. 'reaction-time')
  game_name TEXT NOT NULL,                 -- Human-readable test name
  max_players INT NOT NULL DEFAULT 10,     -- Max participants (10 per room)
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  expires_at TIMESTAMPTZ DEFAULT (timezone('utc'::text, now()) + INTERVAL '48 hours') NOT NULL
);

-- Enable RLS
ALTER TABLE public.battle_rooms ENABLE ROW LEVEL SECURITY;

-- Anyone can read rooms (for joining via link)
CREATE POLICY "Battle rooms are readable by everyone"
ON public.battle_rooms FOR SELECT
USING (true);

-- Anyone can create a room (no auth required)
CREATE POLICY "Anyone can create a battle room"
ON public.battle_rooms FOR INSERT
WITH CHECK (true);

-- Index for fast room_code lookups
CREATE INDEX IF NOT EXISTS idx_battle_rooms_code ON public.battle_rooms(room_code);
CREATE INDEX IF NOT EXISTS idx_battle_rooms_expires ON public.battle_rooms(expires_at);

-- 6. Battle Scores Table (one entry per player per room)
CREATE TABLE IF NOT EXISTS public.battle_scores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id UUID NOT NULL REFERENCES public.battle_rooms(id) ON DELETE CASCADE,
  player_name TEXT NOT NULL,               -- Self-reported player name
  score NUMERIC NOT NULL,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  UNIQUE(room_id, player_name)             -- One score per player name per room
);

-- Enable RLS
ALTER TABLE public.battle_scores ENABLE ROW LEVEL SECURITY;

-- Anyone can read scores (for live leaderboard)
CREATE POLICY "Battle scores are readable by everyone"
ON public.battle_scores FOR SELECT
USING (true);

-- Anyone can submit a score (no auth required)
CREATE POLICY "Anyone can submit a battle score"
ON public.battle_scores FOR INSERT
WITH CHECK (true);

-- Indexes for fast room leaderboard queries
CREATE INDEX IF NOT EXISTS idx_battle_scores_room ON public.battle_scores(room_id);

-- Enable Realtime for live battle leaderboard updates
ALTER PUBLICATION supabase_realtime ADD TABLE public.battle_rooms;
ALTER PUBLICATION supabase_realtime ADD TABLE public.battle_scores;
