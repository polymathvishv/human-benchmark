-- 1. Create Profiles Table
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  username TEXT UNIQUE NOT NULL,
  avatar_color TEXT DEFAULT 'linear-gradient(135deg, #3b82f6 0%, #8b5cf6 100%)',
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Enable Row Level Security (RLS)
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

-- 2. Profiles Security Policies
-- Anyone can view public profiles
CREATE POLICY "Public profiles are viewable by everyone" 
ON public.profiles FOR SELECT 
USING (true);

-- Users can insert their own profile
CREATE POLICY "Users can insert their own profile" 
ON public.profiles FOR INSERT 
WITH CHECK (auth.uid() = id);

-- Users can update their own profile
CREATE POLICY "Users can update their own profile" 
ON public.profiles FOR UPDATE 
USING (auth.uid() = id);

-- 3. Automatic Profile Creation Trigger on Sign Up
CREATE OR REPLACE FUNCTION public.handle_new_user() 
RETURNS TRIGGER AS $$
DECLARE
  initial_username TEXT;
BEGIN
  -- Extract username from user_metadata or fallback to User_XXXX
  initial_username := COALESCE(
    NULLIF(TRIM(new.raw_user_meta_data->>'username'), ''),
    'User_' || SUBSTRING(new.id::text, 1, 6)
  );

  INSERT INTO public.profiles (id, username, avatar_color)
  VALUES (
    new.id,
    initial_username,
    'linear-gradient(135deg, #3b82f6 0%, #8b5cf6 100%)'
  )
  ON CONFLICT (id) DO NOTHING;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Drop trigger if exists and recreate
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;

CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- 4. Create Scores Table (Ready for Cloud Sync)
CREATE TABLE IF NOT EXISTS public.scores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  game_id TEXT NOT NULL,
  score NUMERIC NOT NULL,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Enable RLS on scores
ALTER TABLE public.scores ENABLE ROW LEVEL SECURITY;

-- Anyone can read scores (for leaderboards and stats)
CREATE POLICY "Scores are readable by everyone" 
ON public.scores FOR SELECT 
USING (true);

-- Users can insert their own scores
CREATE POLICY "Users can insert their own scores" 
ON public.scores FOR INSERT 
WITH CHECK (auth.uid() = user_id);

-- Create index on game_id and score for fast querying
CREATE INDEX IF NOT EXISTS idx_scores_game_score ON public.scores(game_id, score);
CREATE INDEX IF NOT EXISTS idx_scores_user ON public.scores(user_id);
